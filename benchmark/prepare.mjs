import { mkdir, readFile, rename, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

import { BENCHMARK_CORPUS, CACHE_DIRECTORY, corpusCachePath, verifyCorpus } from "./corpus.mjs";

await mkdir(CACHE_DIRECTORY, { recursive: true });
const gungraunDirectory = path.join(CACHE_DIRECTORY, "gungraun");
await mkdir(gungraunDirectory, { recursive: true });

const preparedCorpus = [];
for (const corpus of BENCHMARK_CORPUS) {
	const cachePath = corpusCachePath(corpus);
	let buffer = await readCachedCorpus(cachePath);
	if (buffer === null) {
		process.stdout.write(`downloading ${corpus.id}\n`);
		const response = await fetch(corpus.url, {
			redirect: "follow",
			signal: AbortSignal.timeout(60_000),
		});
		if (!response.ok) {
			throw new Error(`Failed to download ${corpus.id}: HTTP ${response.status} ${response.statusText}`);
		}

		buffer = Buffer.from(await response.arrayBuffer());
		verifyCorpus(corpus, buffer, corpus.url);
		await writeCacheFile(cachePath, buffer);
	} else {
		verifyCorpus(corpus, buffer, cachePath);
	}
	await writeCacheFile(gungraunCorpusPath(corpus), buffer);

	preparedCorpus.push({ corpus, source: buffer.toString("utf8") });
	process.stdout.write(`ready      ${corpus.id} (${formatBytes(buffer.length)})\n`);
}

const browserModulePath = `${CACHE_DIRECTORY}/browser-corpus.mjs`;
const browserModule =
	"// Generated by benchmark/prepare.mjs. Do not edit.\n" +
	`export const BENCHMARK_CORPUS = ${JSON.stringify(
		preparedCorpus.map(({ corpus, source }) => ({
			id: corpus.id,
			label: corpus.label,
			lang: corpus.lang,
			upstreamPath: corpus.upstreamPath,
			bytes: corpus.bytes,
			source,
		})),
	)};\n`;
await writeCacheFile(browserModulePath, Buffer.from(browserModule));

function readCachedCorpus(cachePath) {
	return readFile(cachePath).catch((error) => {
		if (error.code === "ENOENT") {
			return null;
		}
		throw error;
	});
}

async function writeCacheFile(cachePath, buffer) {
	const temporaryPath = `${cachePath}.tmp-${process.pid}-${Date.now()}`;
	try {
		await writeFile(temporaryPath, buffer, { flag: "wx" });
		await rename(temporaryPath, cachePath);
	} catch (error) {
		await unlink(temporaryPath).catch(() => undefined);
		throw error;
	}
}

function formatBytes(bytes) {
	return `${(bytes / 1024).toFixed(1)} KiB`;
}

function gungraunCorpusPath(corpus) {
	const extension = path.extname(corpus.upstreamPath);
	return path.join(gungraunDirectory, `${corpus.id}${extension}`);
}
